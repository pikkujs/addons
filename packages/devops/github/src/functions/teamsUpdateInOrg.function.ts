export const TeamsUpdateInOrgInput = z.object({
  org: z.string().describe("The organization name. The name is not case sensitive."),
  team_slug: z.string().describe("The slug of the team name."),
  description: z.string().optional().describe("The description of the team."),
  name: z.string().optional().describe("The name of the team."),
  parent_team_id: z.number().int().nullable().optional().describe("The ID of a team to set as the parent team."),
  permission: z.enum(["pull", "push", "admin"]).optional().default("pull").describe("**Deprecated**. The permission that new repositories will be added to the team with when none is specified."),
  privacy: z.enum(["secret", "closed"]).optional().describe("The level of privacy this team should have. Editing teams without specifying this parameter leaves `privacy` intact. When a team is nested, the `privacy` for parent teams cannot be `secret`. The options are:  \n**For a non-nested team:**  \n * `secret` - only visible to organization owners and members of this team.  \n * `closed` - visible to all members of this organization.  \n**For a parent or child team:**  \n * `closed` - visible to all members of this organization."),
})

