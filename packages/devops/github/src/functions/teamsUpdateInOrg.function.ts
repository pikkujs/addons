export const teamsUpdateInOrg = pikkuSessionlessFunc({
  description: "To edit a team, the authenticated user must either be an organization owner or a team maintainer.\n\n**Note:** You can also specify a team by `org_id` and `team_id` using the route `PATCH /organizations/{org_id}/team/{team_id}`.",
  input: TeamsUpdateInOrgInput,
  output: TeamsUpdateInOrgOutput,
  errors: [ForbiddenError, NotFoundError, UnprocessableContentError],
  func: async ({ github }, data) => {
    return github.call("PATCH", "/orgs/{org}/teams/{team_slug}", data) as any
  },
})
